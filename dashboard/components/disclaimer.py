"""Shared official data disclaimer banner component for the KMDA dashboard."""
import streamlit as st


def render_disclaimer_banner(context: str = "general") -> None:
    """Renders a prominent official data disclaimer banner across all dashboard pages."""
    text_by_context = {
        "general": (
            "**[OFFICIAL DATA DISCLAIMER]** This system currently operates on **synthetically generated "
            "crash data** statistically calibrated to MoRTH national accident profiles for the Kolkata "
            "Metropolitan Area. Official Kolkata Police FIR and KMDA field records have **not yet been "
            "ingested**. All risk rankings, SHAP feature drivers, and model probabilities represent a "
            "decision-support prototype and **must not be used for operational civil works** without ground-truth verification."
        ),
        "hotspots": (
            "**[OFFICIAL DATA DISCLAIMER]** Road segment risk tiers and hotspot indices below are derived "
            "from **synthetic crash distributions** snapped to Kolkata road corridors. Grey segments denote "
            "unmonitored stretches with no simulated crash data. Do not use for operational enforcement allocation."
        ),
        "shap": (
            "**[OFFICIAL DATA DISCLAIMER]** SHAP importance attributions and local risk factors below reflect "
            "patterns learned from **synthetic training data**. While directional relationships match road safety "
            "engineering literature, specific feature magnitudes must be calibrated against official Kolkata Police records."
        ),
        "simulator": (
            "**[OFFICIAL DATA DISCLAIMER]** Counterfactual probability shifts simulated below are generated by an "
            "XGBoost model calibrated on **synthetic prototype data**. Probability deltas should be interpreted as "
            "directional sensitivity benchmarks, not certified actuarial guarantees."
        ),
        "policy": (
            "**[OFFICIAL POLICY DISCLAIMER]** This executive briefing and countermeasure priority list is a "
            "**methodological proof-of-concept**. All crash frequencies, blackspot rankings, and civil expenditure tiers "
            "are simulated. Physical tendering requires ingestion of official Kolkata Police incident databases."
        ),
    }

    message = text_by_context.get(context, text_by_context["general"])
    st.warning(message)


def render_sidebar_disclaimer() -> None:
    """Renders a persistent prototype status block in the sidebar."""
    st.sidebar.markdown("---")
    st.sidebar.caption(
        "**System Status:** Prototype (Synthetic Data)\n\n"
        "Calibrated to MoRTH national statistics. Pending official Kolkata Police / KMDA FIR integration."
    )
